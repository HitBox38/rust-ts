#!/bin/sh
# Regenerates src/miri/shims/unix/virtual_socket.oracle.txt with the isolated Miri (never ~/.rustup; lane miri-tail-b).
# Usage: RUST_TS_DATA=... sh docs/handoff/miri-tail-b-probe/run.sh
set -u
DIR=$(cd "$(dirname "$0")" && pwd)
OUT="$DIR/../../../src/miri/shims/unix/virtual_socket.oracle.txt"
WORK="$RUST_TS_DATA/tmp/miri-tail-b"
TC=nightly-2026-10-11-aarch64-apple-darwin
MIRI="$RUST_TS_DATA/rustup-miri/toolchains/$TC/bin/miri"
miri() {
  env -i HOME="$HOME" PATH=/usr/bin:/bin RUSTUP_HOME="$RUST_TS_DATA/rustup-miri" CARGO_HOME="$RUST_TS_DATA/cargo-miri" \
    "$MIRI" --sysroot "$RUST_TS_DATA/miri-sysroot" --target x86_64-unknown-linux-gnu "$@"
}
mkdir -p "$WORK"
cd "$WORK" || exit 1
cp "$DIR"/probe.rs "$DIR"/metadata.rs "$DIR"/err_*.rs .
{
  echo "# GENERATED by the pinned Miri (isolated oracle, x86_64-unknown-linux-gnu) from docs/handoff/miri-tail-b-probe; see docs/handoff/miri-tail-b.md."
  miri probe.rs 2>probe.stderr >probe.stdout
  code=$?
  sed 's/^/out /' probe.stdout
  echo "exit $code"
  # fstat needs isolation off (the virtual sockets' `metadata` never touches the host).
  miri -Zmiri-disable-isolation metadata.rs 2>meta.stderr >meta.stdout
  code=$?
  sed 's/^/metadata /' meta.stdout
  echo "metadata exit $code"
  for f in err_*.rs; do
    miri "$f" 2>err.stderr >/dev/null
    code=$?
    # The first error line is the message; the rest names local paths.
    echo "err ${f%.rs} exit=$code $(grep -m1 -E '^(error|thread)' err.stderr)"
  done
} >"$OUT"
