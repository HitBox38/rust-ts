/** `let original = r##"…"##;` inputs of one pulldown-cmark test file. */
function suite_inputs(file: string): string[] {
  const src = readFileSync(file, "utf8");
  return [...src.matchAll(/let original = r##"([\s\S]*?)"##;/g)].map((m) => m[1]!);
}

function walk_rs(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir).sort()) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk_rs(p, out);
    else if (e.endsWith(".rs")) out.push(p);
  }
  return out;
}

/** Consecutive `///` (outer) or `//!` (inner) lines of a file, as doc attributes. */
function doc_blocks(file: string): [string, string, string][][] {
  const out: [string, string, string][][] = [];
  let cur: [string, string, string][] = [];
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = /^\s*\/\/([\/!])(.*)$/.exec(line);
    if (m !== null && !(m[1] === "/" && m[2]!.startsWith("/"))) {
      cur.push(L(m[1] === "!" ? "inner" : "outer", m[2]!));
    } else if (cur.length > 0) {
      out.push(cur);
      cur = [];
    }
  }
  if (cur.length > 0) out.push(cur);
  return out;
}

/** Deterministic PRNG (mulberry32). */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const FUZZ_TOKENS = [
  "[", "]", "(", ")", "*", "**", "_", "__", "`", "``", "```", "~", "~~", "<", ">", "!", "\\", "\n", "\n\n", "\r\n",
  " ", "  ", "    ", "\t", "|", "-", "---", "#", "## ", "> ", "1. ", "- ", "* ", "+ ", "$", "$$", "\"", "'", "&amp;", "&#x41;",
  "&bogus;", ":", "^", "[^1]", "[^1]: ", "[a]: ", "<a>", "</a>", "<!--", "-->", "<?", "?>", "<![CDATA[", "]]>", "http://x.y",
  "a@b.c", "foo", "bar", "Vec<T>", "::", "ä", "ΣΑΣ", "K", "{#id .c}", "- [ ] ", "- [x] ", "===", "+++", "...", "--",
  "a", "b", "x", "1", "\\|", "[`", "`]", "](", "][", "[]", "<http://a>", "{", "}", "=", "\"t\"",
];

/** Random markdown made of `FUZZ_TOKENS` (deterministic per seed). */
function fuzz_docs(seed: number, count: number): string[] {
  const r = rng(seed);
  const toks = FUZZ_TOKENS;
  const out: string[] = [];
  for (let i = 0; i < count; i++) {
    const n = 1 + Math.floor(r() * 40);
    let s = "";
    for (let k = 0; k < n; k++) s += toks[Math.floor(r() * toks.length)]!;
    out.push(s);
  }
  return out;
}

export function build_corpus(): Entry[] {
  const entries: Entry[] = [];
  for (const a of HANDWRITTEN) entries.push({ t: "doc", a });
  for (const s of STRIP) entries.push({ t: "strip", s });
  const pc = join(process.env.HOME ?? "", ".cargo/registry/src/index.crates.io-1949cf8c6b5b557f/pulldown-cmark-0.11.3/tests/suite");
  if (!existsSync(pc)) throw new Error(`ERROR: pulldown-cmark-0.11.3 source not found (bun scripts/crate-src.ts pulldown-cmark): ${pc}`);
  for (const f of readdirSync(pc).sort()) {
    if (!f.endsWith(".rs")) continue;
    const opts = f === "old_footnotes.rs" ? [0, MAIN, OLD_FOOTNOTES] : [0, MAIN, ALL];
    for (const s of suite_inputs(join(pc, f))) entries.push({ t: "md", o: opts, s });
  }
  return entries;
}

/** Entries regenerated on every load (deterministic, not committed): the token soups and the
 *  doc-comment blocks of the upstream checkout at the pin. */
export function generated_entries(): Entry[] {
  const entries: Entry[] = [];
  for (const s of fuzz_docs(1, 3000)) entries.push({ t: "md", o: [MAIN, ALL], s });
  for (const crate of ["rustc_resolve", "rustc_ast"]) {
    const dir = join(DATA, "rust", "compiler", crate, "src");
    if (!existsSync(dir)) throw new Error(`ERROR: upstream checkout missing: ${dir}`);
    for (const f of walk_rs(dir)) {
      for (const a of doc_blocks(f)) entries.push({ t: "doc", a });
    }
  }
  return entries;
}

if (import.meta.main) {
  const cmd = process.argv[2];
  if (cmd === "corpus") {
    const entries = build_corpus();
    writeFileSync(CORPUS, entries.map((e) => JSON.stringify(e)).join("\n") + "\n");
    console.log(`corpus.jsonl: ${entries.length} entries; with the generated ones ${load_corpus().length} cases`);
  } else if (cmd === "fixture") {
    const cases = load_corpus();
    const outs = probe(cases);
    if (outs.length !== cases.length) throw new Error(`ERROR: probe answered ${outs.length} of ${cases.length} cases`);
    const header = "# SHA-256 prefixes of the rustdoc probe's output per case of corpus.jsonl (see corpus.ts).\n";
    writeFileSync(EXPECTED, header + outs.map(digest).join("\n") + "\n");
    console.log(`expected.txt: ${outs.length} cases`);
  } else if (cmd === "diff") {
    const limit = Number(process.argv[3] ?? 20);
    const cases = load_corpus();
    const want = probe(cases);
    const got = replay(cases);
    let bad = 0;
    for (let i = 0; i < cases.length; i++) {
      if (want[i] === got[i]) continue;
      bad++;
      if (bad <= limit) {
        const w = want[i]!.split("\n");
        const g = got[i]!.split("\n");
        let k = 0;
        while (k < w.length && w[k] === g[k]) k++;
        console.log(`case ${i} ${JSON.stringify(cases[i]).slice(0, 200)}\n  want: ${w[k]}\n  got:  ${g[k]}`);
      }
    }
    console.log(`${cases.length - bad}/${cases.length} cases match`);
  } else {
    console.log("usage: corpus.ts corpus | fixture | diff [n]");
  }
}
