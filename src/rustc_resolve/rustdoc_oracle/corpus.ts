// Corpus and replay for the `rustdoc` probe (tools/probes/rustdoc/main.rs documents the case format
// and the output) and src/rustc_resolve/rustdoc_oracle.test.ts (lane rustdoc).
//
//   bun src/rustc_resolve/rustdoc_oracle/corpus.ts corpus    rebuild corpus.jsonl from the sources below
//   bun src/rustc_resolve/rustdoc_oracle/corpus.ts fixture   rewrite expected.txt from the probe
//   bun src/rustc_resolve/rustdoc_oracle/corpus.ts diff [n]  print the first differing line per case
//
// corpus.jsonl (committed: the handwritten, strip and pulldown-cmark suite entries; the token soups and
// the doc-comment blocks are regenerated by `generated_entries` on every load): one JSON entry per line:
//   {"t":"doc","a":[[kind,style,text],...]}  an item's doc attributes (kind line|block|raw, style outer|inner)
//   {"t":"md","o":[opts...],"s":text}       a markdown text, run once per `Options` bits value
//   {"t":"strip","s":path}                  a `strip_generics_from_path` input
// Sources: the handwritten cases below; every input of pulldown-cmark 0.11.3's own test suite
// (tests/suite/*.rs `let original = r##"…"##;`), with the option sets of its `test_markdown_html` and with
// `main_body_opts()`; 3000 random token soups (`fuzz_docs(1, 3000)`); and the `///` / `//!` doc-comment blocks of compiler/rustc_resolve and
// compiler/rustc_ast at the pin (real intra-doc links).
// expected.txt (committed): after `#` lines, one line per expanded case: the first 16 hex digits of the
// SHA-256 of the probe's output for that case.
