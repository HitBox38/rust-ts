export type Entry =
  | { t: "doc"; a: [string, string, string][] }
  | { t: "md"; o: number[]; s: string }
  | { t: "strip"; s: string };

/** One probe case. */
export type Case = { t: "doc"; a: [string, string, string][] } | { t: "md"; o: number; s: string } | { t: "strip"; s: string };

export function expand(entries: readonly Entry[]): Case[] {
  const out: Case[] = [];
  for (const e of entries) {
    if (e.t === "md") for (const o of e.o) out.push({ t: "md", o, s: e.s });
    else out.push(e);
  }
  return out;
}

/** corpus.jsonl followed by the generated entries (`generated_entries`), expanded to probe cases. */
export function load_corpus(): Case[] {
  const committed = readFileSync(CORPUS, "utf8")
    .split("\n")
    .filter((l) => l.length > 0)
    .map((l) => JSON.parse(l) as Entry);
  return expand([...committed, ...generated_entries()]);
}

const hex = (s: string): string => (s.length === 0 ? "_" : Buffer.from(s, "utf8").toString("hex"));

/** The probe's stdin for `cases`. */
export function probe_input(cases: readonly Case[]): string {
  let out = "";
  for (const c of cases) {
    if (c.t === "doc") for (const [k, st, text] of c.a) out += `doc ${k} ${st} ${hex(text)}\n`;
    else if (c.t === "md") out += `md ${c.o} ${hex(c.s)}\n`;
    else out += `strip ${hex(c.s)}\n`;
    out += "end\n";
  }
  return out;
}

/** Runs the probe; its output split per case (each chunk starts with `case <n>`). */
export function probe(cases: readonly Case[]): string[] {
  const r = Bun.spawnSync([PROBE], { stdin: Buffer.from(probe_input(cases)), stdout: "pipe", stderr: "pipe" });
  if (r.exitCode !== 0) throw new Error(`ERROR: rustdoc probe exited ${r.exitCode}: ${r.stderr.toString().split("\n")[0]}`);
  return split_cases(r.stdout.toString());
}

export function split_cases(s: string): string[] {
  const parts = s.split(/^(?=case \d+\n)/m);
  return parts.filter((p) => p.length > 0);
}

export function digest(s: string): string {
  return createHash("sha256").update(s).digest("hex").slice(0, 16);
}

// ---- the TS side of the probe's report ----

const q = debug_str;
const opt_str = (s: string | undefined): string => (s === undefined ? "None" : `Some(${q(s)})`);
const opt_dbg = (s: string | number | undefined): string => (s === undefined ? "None" : `Some(${s})`);

function fmt_tag(t: Tag): string {
  switch (t.$) {
    case "Heading":
      return `Heading(${t.level}, ${opt_str(t.id)}, [${t.classes.map(q).join(", ")}], [${t.attrs.map(([a, b]) => `(${q(a)}, ${opt_str(b)})`).join(", ")}])`;
    case "BlockQuote":
      return `BlockQuote(${opt_dbg(t._0)})`;
    case "CodeBlock":
      return t._0.$ === "Indented" ? "CodeBlock(Indented)" : `CodeBlock(Fenced(${q(t._0._0)}))`;
    case "List":
      return `List(${opt_dbg(t._0)})`;
    case "FootnoteDefinition":
      return `FootnoteDefinition(${q(t._0)})`;
    case "Table":
      return `Table([${t._0.join(", ")}])`;
    case "Link":
    case "Image":
      return `${t.$}(${t.link_type}, ${q(t.dest_url)}, ${q(t.title)}, ${q(t.id)})`;
    case "MetadataBlock":
      return `MetadataBlock(${t._0})`;
    default:
      return t.$;
  }
}

function fmt_tag_end(t: TagEnd): string {
  switch (t.$) {
    case "Heading":
    case "MetadataBlock":
      return `${t.$}(${t._0})`;
    case "List":
      return `List(${t._0})`;
    default:
      return t.$;
  }
}

function fmt_event(e: Event): string {
  switch (e.$) {
    case "Start":
      return `Start(${fmt_tag(e._0)})`;
    case "End":
      return `End(${fmt_tag_end(e._0)})`;
    case "Text":
    case "Code":
    case "InlineMath":
    case "DisplayMath":
    case "Html":
    case "InlineHtml":
    case "FootnoteReference":
      return `${e.$}(${q(e._0)})`;
    case "TaskListMarker":
      return `TaskListMarker(${e._0})`;
    default:
      return e.$;
  }
}

function cmp_bytes(a: string, b: string): number {
  return Buffer.compare(Buffer.from(a, "utf8"), Buffer.from(b, "utf8"));
}

function markdown_report(md: string, opts: Options): string {
  let out = "";
  const it = Parser.new_ext(Str.from(md), opts).into_offset_iter();
  for (let r = it.next(); r !== undefined; r = it.next()) {
    out += `ev ${fmt_event(r[0])} ${r[1][0]}..${r[1][1]}\n`;
  }
  const defs = it.reference_definitions().iter();
  defs.sort((a, b) => cmp_bytes(a[0], b[0]));
  for (const [label, def] of defs) out += `def ${q(label)} ${q(def.dest)} ${opt_str(def.title)}\n`;
  for (const l of parse_links(md)) out += `link ${q(l)}\n`;
  return out;
}

/** The TS port's report for `cases` (same format as the probe's). */
export function replay(cases: readonly Case[]): string[] {
  return create_default_session_globals_then(() => {
    const g = attr.AttrIdGenerator.new();
    const outs: string[] = [];
    cases.forEach((c, n) => {
      let out = `case ${n}\n`;
      if (c.t === "md") {
        out += markdown_report(c.s, c.o);
      } else if (c.t === "strip") {
        const r = strip_generics_from_path(c.s);
        out += `strip ${r.$ === "Ok" ? `Ok(${q(r._0)})` : `Err(${r._0})`}\n`;
      } else {
        const attrs = c.a.map(([k, st, text]) => {
          const style: AttrStyle = st === "inner" ? "Inner" : "Outer";
          const data = Symbol.intern(text);
          if (k === "line") return attr.mk_doc_comment(g, "Line", style, data, DUMMY_SP);
          if (k === "block") return attr.mk_doc_comment(g, "Block", style, data, DUMMY_SP);
          return attr.mk_attr_name_value_str(g, style, sym.doc, data, DUMMY_SP);
        });
        const [frags, others] = attrs_to_doc_fragments(
          attrs.map((a) => [a, undefined] as const),
          false,
          attr.AttributeExt.Attribute,
        );
        if (others.length !== 0) throw new Error("non-doc attribute");
        for (const f of frags) {
          const kind = f.kind.$ === "Sugared" ? `Sugared(${f.kind._0})` : "Raw";
          const indent = f.indent === Infinity ? "MAX" : String(f.indent);
          out += `frag ${q(Symbol.as_str(f.doc))} ${kind} ${indent} ${f.style}\n`;
        }
        const docs = prepare_to_doc_link_resolution(frags);
        for (const d of docs.values()) out += `docs ${q(d.outer)} ${q(d.inner)}\n`;
        const first = docs.values().next();
        if (!first.done) out += markdown_report(first.value.outer + first.value.inner, main_body_opts());
      }
      outs.push(out);
    });
    return outs;
  });
}

