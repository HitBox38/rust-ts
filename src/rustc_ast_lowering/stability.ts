// rustc: compiler/rustc_ast_lowering/src/stability.rs:10 enabled_names
export function enabled_names(features: Features, span: Span): string[] {
  return ExternAbi.ALL_VARIANTS.filter((abi) => extern_abi_enabled(features, span, abi).$ === "Ok").map((abi) =>
    ExternAbi.as_str(abi),
  );
}

// rustc: compiler/rustc_ast_lowering/src/stability.rs:18 extern_abi_enabled
export function extern_abi_enabled(features: Features, span: Span, abi: ExternAbi): Result<undefined, UnstableAbi> {
  // `.or_else(|unstable @ UnstableAbi { feature, .. }| ..)`
  const r = extern_abi_stability(abi);
  if (r.$ === "Ok") return r;
  const unstable = r._0;
  const { feature } = unstable;
  if (features.enabled(feature) || Span.allows_unstable(span, feature)) {
    return Ok(undefined);
  } else {
    return Err(unstable);
  }
}

// rustc: compiler/rustc_ast_lowering/src/stability.rs:32 gate_unstable_abi
export function gate_unstable_abi(sess: Session, features: Features, span: Span, abi: ExternAbi): void {
  const r = extern_abi_enabled(features, span, abi);
  switch (r.$) {
    case "Ok":
      break;
    case "Err": {
      const unstable_abi = r._0;
      const explain = display_UnstableAbi(unstable_abi);
      feature_err(sess, unstable_abi.feature, span, explain).emit();
      break;
    }
  }
}

// impl fmt::Display for UnstableAbi
// rustc: compiler/rustc_ast_lowering/src/stability.rs:54 fmt
export function display_UnstableAbi(self: UnstableAbi): string {
  const { abi } = self;
  switch (self.explain) {
    case "Experimental":
      return `the extern ${display_ExternAbi(abi)} ABI is experimental and subject to change`;
    case "ImplDetail":
      return `the extern ${display_ExternAbi(abi)} ABI is an implementation detail and perma-unstable`;
  }
}

// rustc: compiler/rustc_ast_lowering/src/stability.rs:67 extern_abi_stability
export function extern_abi_stability(abi: ExternAbi): Result<undefined, UnstableAbi> {
  switch (abi.$) {
    // stable ABIs
    case "Rust":
    case "C":
    case "Cdecl":
    case "Custom":
    case "Stdcall":
    case "Fastcall":
    case "Thiscall":
    case "Aapcs":
    case "Win64":
    case "SysV64":
    case "System":
    case "EfiApi":
      return Ok(undefined);
    case "LlvmIntrinsic":
      return Err({
        abi,
        feature: sym.link_llvm_intrinsics,
        explain: GateReason.ImplDetail,
      });
    // experimental
    case "Vectorcall":
      return Err({
        abi,
        feature: sym.abi_vectorcall,
        explain: GateReason.Experimental,
      });
    case "RustCall":
      return Err({
        abi,
        feature: sym.unboxed_closures,
        explain: GateReason.Experimental,
      });
    case "RustCold":
      return Err({ abi, feature: sym.rust_cold_cc, explain: GateReason.Experimental });
    case "RustPreserveNone":
      return Err({
        abi,
        feature: sym.rust_preserve_none_cc,
        explain: GateReason.Experimental,
      });
    case "RustTail":
      return Err({ abi, feature: sym.rust_tail_cc, explain: GateReason.Experimental });
    case "RustInvalid":
      return Err({ abi, feature: sym.rustc_attrs, explain: GateReason.ImplDetail });
    case "GpuKernel":
      return Err({
        abi,
        feature: sym.abi_gpu_kernel,
        explain: GateReason.Experimental,
      });
    case "PtxKernel":
      return Err({ abi, feature: sym.abi_ptx, explain: GateReason.Experimental });
    case "Msp430Interrupt":
      return Err({
        abi,
        feature: sym.abi_msp430_interrupt,
        explain: GateReason.Experimental,
      });
    case "X86Interrupt":
      return Err({
        abi,
        feature: sym.abi_x86_interrupt,
        explain: GateReason.Experimental,
      });
    case "AvrInterrupt":
    case "AvrNonBlockingInterrupt":
      return Err({
        abi,
        feature: sym.abi_avr_interrupt,
        explain: GateReason.Experimental,
      });
    case "RiscvInterruptM":
    case "RiscvInterruptS":
      return Err({
        abi,
        feature: sym.abi_riscv_interrupt,
        explain: GateReason.Experimental,
      });
    case "CmseNonSecureCall":
      return Err({
        abi,
        feature: sym.abi_cmse_nonsecure_call,
        explain: GateReason.Experimental,
      });
    case "CmseNonSecureEntry":
      return Err({
        abi,
        feature: sym.cmse_nonsecure_entry,
        explain: GateReason.Experimental,
      });
    case "Swift":
      return Err({ abi, feature: sym.abi_swift, explain: GateReason.Experimental });
  }
}
