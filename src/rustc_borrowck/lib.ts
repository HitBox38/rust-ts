// rustc: compiler/rustc_borrowck/src/lib.rs:605 get_flow_results
function get_flow_results(tcx: TyCtxt, body: Body, move_data: MoveData, borrow_set: BorrowSet, regioncx: RegionInferenceContext): Results<BorrowckDomain, Borrowck> {
  // We compute these three analyses individually, but them combine them into
  // a single results so that `mbcx` can visit them all together.
  const borrows = Borrows.new(tcx, body, regioncx, borrow_set).iterate_to_fixpoint(tcx, body, "borrowck");
  const uninits = MaybeUninitializedPlaces.new(tcx, body, move_data).iterate_to_fixpoint(tcx, body, "borrowck");
  const ever_inits = EverInitializedPlaces.new(body, move_data).iterate_to_fixpoint(tcx, body, "borrowck");
  // PORT: the `tcx.prof.generic_activity("borrowck_dataflow_*")` timers are not kept (the profiler stand-in records
  // nothing, driver-m2 decision 8).

  const analysis = new Borrowck(borrows.analysis, uninits.analysis, ever_inits.analysis);

  assert(borrows.entry_states.length === uninits.entry_states.length, "assertion failed: `(left == right)`");
  assert(borrows.entry_states.length === ever_inits.entry_states.length, "assertion failed: `(left == right)`");
  const entry_states: BorrowckDomain[] = borrows.entry_states.map((borrows_, i) => ({
    borrows: borrows_,
    uninits: uninits.entry_states[i]!,
    ever_inits: ever_inits.entry_states[i]!,
  }));

  return new Results(analysis, entry_states);
}

