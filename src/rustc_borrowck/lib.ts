//   classes' it extends), the hand classes' defining modules (type_check/mod.ts for `TypeChecker`) and other crates.
// - Hand modules import other modules' generated items (types, companions, debug_ / clone_ fns, newtype helpers) from
//   their `.gen.ts`, as the generated code does (set option `import_gen`), and only hand-written items (ported fns,
//   hand classes, manual impls) from hand modules. Rust `pub use x::*` of a sibling module that assigns prototypes
