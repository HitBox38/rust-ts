// ---- Contract conventions (every rustc_borrowck module; recorded in the handoff) --------------------------------------
// Types
// - Every type of the crate is generated by tools/codegen/types.ts (set `rustc_borrowck`, type map
//   tools/codegen/borrowck.typemap.json) into `<file>.gen.ts`; each hand module `export * from "./<file>.gen.ts"`.
//   Structs with an inherent impl are classes (constructor = all fields in declaration order). `MirBorrowckCtxt`,
//   `BorrowckInferCtxt` (lib.gen.ts), `RegionInferenceContext` (region_infer/region_context.gen.ts),
//   `BorrowCheckRootCtxt` (root_cx.gen.ts), `UniversalRegions`, `BorrowSet`, `RegionValues`, ... are generated classes.
// - Hand types (`hand` in the set; a class in the mirrored hand module, fields in declaration order, constructor takes
//   all fields): `TypeChecker` (type_check/mod.ts, extends rustc_middle mir/visit.ts's `Visitor`), the module-level MIR
//   visitors (`GatherBorrows`, `GatherUsedMutsVisitor`, `AllLocalUsesVisitor`, `DefUseVisitor`, `LiveVariablesVisitor`,
//   `LocalUseMapBuild`, the polonius legacy generators: extend `Visitor`; `RegionRenumberer` extends `MutVisitor`), the
//   HIR visitors (`BindingFinder`, `ReferencedStatementsVisitor`, `BreakFinder`, `ConditionVisitor`: extend rustc_hir
//   intravisit's `Visitor`) and the analyses `Borrows` / `Borrowck` (dataflow.ts, extend rustc_mir_dataflow's
//   `AnalysisBase`, dataflow-contract D5).
// - Struct-keyed maps / sets (`FxIndexSet<(Place, Span)>`, `FxIndexMap<Location, _>`, ...) are `KeyedMap` / `KeyedSet`
//   (rust_ts/keyed.ts) at construction; their declared type stays `Map` / `Set` (builder-contract decision 6).
//   `BTreeMap` / `BTreeSet` are `Map` / `Set` whose users keep key order. `Frozen<T>` is `T`. `Rc<T>` / `&T` are `T`.
//   `OnceCell<T>` is `T | undefined`. `RefCell<T>` / `Cell<T>` are the field itself. `()` as a type argument is `null`.
// Methods
// - Methods of a generated class are declared by the file holding the `impl` block, in
//   `declare module "<rel>/<file>.gen.ts" { interface X { /* <file>.rs:<line> (lane <lane>) */ name(..): R; } }`, and
//   assigned in upstream order: `X.prototype.name = function (this: X, ..): R { .. };`. Associated fns without `self`
//   are statics declared in `namespace X { function name(..): R; }` of the same augmentation (`new` is
//   `function new_(..): X; export { new_ as new }`) and assigned `(X as unknown as { name: typeof X.name }).name = ..`.
// - Methods of a hand class are in its class body when the impl block is in the defining file, else augmented the same
//   way on the defining hand module (`declare module "./mod.ts" { interface TypeChecker { .. } }`).
// - A method whose name is also a field of its class gets a trailing `_` (mir-contract decision): `MirBorrowckCtxt`'s
//   `body_()` / `local_names_()`, `BorrowCheckRootCtxt.root_def_id_()`, `TypeChecker.body_()`, ... A trait method
//   fixed by an interface keeps its name and the colliding field gets the `_` instead.
// - Enum methods live on the companion (PORTING §8): the hand module does `import * as gen from "./<file>.gen.ts"`,
//   declares `export interface E_methods { name(self: E, ..): R; }`, `export type E = gen.E;`,
//   `export const E = gen.E as typeof gen.E & E_methods;` and assigns `E.name = function (self: E, ..) { .. }`
//   (builder-contract precedent, matches/mod.ts). A companion the generator did not emit is `{} as E_methods`.
// - Trait impls: on a class, the trait's methods are prototype methods (`impl Visitor for X` overrides the base class
//   methods; `TypeVisitor` / `FallibleTypeFolder` / `TypeRelation` / `TypeOutlivesDelegate` / `Iterator` / `Index` are
//   interfaces implemented by prototype methods). Extension traits (`#[extension(pub trait PlaceExt)] impl Place`,
//   `InferCtxtExt for InferCtxt`) augment the foreign class's defining module (errctxt-contract `ObligationCauseExt`
//   precedent). A trait implemented by non-class values is an impl table `<Trait>_<Type>` (dataflow-contract
//   `GenKill_DenseBitSet` precedent); a crate trait is an `interface` whose required methods carry `// rustc:` markers
//   (declarations, nothing to port) and whose provided methods live in `<Trait>_provided` (PORTING §8).
//   `Deref` is a field + rust_ts/deref.ts `register_deref` (fnctxt-contract): `BorrowckInferCtxt -> InferCtxt` (here),
//   `RegionInferenceContext` / `UnsolvedRegionInferenceContext -> RegionInferenceContextInner` (region_context.ts);
//   lib.ts calls `install_derefs()` after every module is loaded.
// - Fn-local items (nested fns, local structs and their impls) are module level until their fill lane moves them inside
//   (dataflow-contract decision 8), named as upstream.
// Signatures (PORTING §5): `&self` / `&mut self` -> `this`; `&mut T` out-parameters of copy values -> `MutRef<T>`;
//   closures / `impl Fn*` -> arrow types `(a0: A) => R`; `impl Iterator<Item = T>` -> `Iterable<T>`; generic trait
//   bounds that dispatch -> impl-table parameters last (`T_`); `Diag<'_>` -> rustc_errors `Diag`; `fmt::Result`-writing
//   `&mut Formatter` -> the fn returns the text.
// Stubs: `// stub: compiler/rustc_borrowck/src/<file>:<line> <name> (lane <lane>)` directly above the declaration,
//   whose body is `return unported("rustc_borrowck::<module>[::<SelfType>]::<name>");` (the module of the fn's own
//   file: `rustc_borrowck` for lib.rs, `rustc_borrowck::type_check` for type_check/mod.rs). Filling one: keep the
//   signature, port the body in place, turn the comment into `// rustc: <path>:<line> <name>`, lower the counts in
//   contract.test.ts.
// Init order (TDZ-free; contract.test.ts loads every module as a fresh entry point):
