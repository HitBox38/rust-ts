/// Start borrow checking by collecting the region constraints for
/// the current body. This initializes the relevant data structures
/// and then type checks the MIR body.
// rustc: compiler/rustc_borrowck/src/lib.rs:318 borrowck_collect_region_constraints
export function borrowck_collect_region_constraints(root_cx: BorrowCheckRootCtxt, def: LocalDefId): CollectRegionConstraintsResult {
  const tcx = root_cx.tcx;
  const infcx = BorrowckInferCtxt.new(tcx, def, root_cx.root_def_id_());
  const [input_body_steal, promoted_steal] = tcx.mir_promoted(def);
  const input_body: Body = input_body_steal.borrow();
  const input_promoted: readonly Body[] = promoted_steal.borrow();
  if (input_body.tainted_by_errors !== undefined) {
    infcx.set_tainted_by_errors(input_body.tainted_by_errors);
  }

  // Replace all regions with fresh inference variables. This
  // requires first making our own copy of the MIR. This copy will
  // be modified (in place) to contain non-lexical lifetimes. It
  // will have a lifetime tied to the inference context.
  const body_owned = clone_Body(input_body);
  const promoted = input_promoted.map(clone_Body);
  const universal_regions = nll.replace_regions_in_mir(infcx, body_owned, promoted);
  const body = body_owned; // no further changes

  const location_table = PoloniusLocationTable.new(body);

  const move_data = MoveData.gather_moves(body, tcx, (_) => true);

  const locals_are_invalidated_at_exit = BodyOwnerKind.is_fn_or_closure(tcx.hir_body_owner_kind(def));
  const borrow_set = BorrowSet.build(tcx, body, locals_are_invalidated_at_exit, move_data);

  const location_map = DenseLocationMap.new(body);

  const polonius_input =
    (root_cx.consumer !== undefined && root_cx.consumer.polonius_input()) || Polonius.is_legacy_enabled(infcx.tcx.sess.opts.unstable_opts.polonius);
  // PORT: `Option<PoloniusFacts>` is a `MutRef` slot (`&mut polonius_facts` is handed to `type_check`);
  // `PoloniusFacts::default()` is `unknown` until vendor polonius-engine is ported (plan-m4 D7, wave 26).
  const polonius_facts: { value: PoloniusFacts | undefined } = {
    value: polonius_input || PoloniusFactsExt.enabled(infcx.tcx) ? PoloniusFacts_default() : undefined,
  };

  // Run the MIR type-checker.
  const {
    constraints,
    universal_region_relations,
    region_bound_pairs,
    known_type_outlives_obligations,
    deferred_closure_requirements,
    polonius_context,
  }: MirTypeckResults = type_check(
    infcx,
    body,
    promoted,
    universal_regions,
    location_table,
    borrow_set,
    polonius_facts,
    move_data,
    location_map,
  );

  return {
    infcx,
    body_owned,
    promoted,
    move_data,
    borrow_set,
    location_table,
    location_map,
    universal_region_relations,
    region_bound_pairs,
    known_type_outlives_obligations,
    constraints,
    deferred_closure_requirements,
    deferred_opaque_type_errors: [],
    polonius_facts: polonius_facts.value,
    polonius_context,
  };
}

