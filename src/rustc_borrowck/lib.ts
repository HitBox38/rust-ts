/// Provider for `query mir_borrowck`. Unlike `typeck`, this must
/// only be called for typeck roots which *similar* to `typeck` will
/// then borrowck all nested bodies as well.
// rustc: compiler/rustc_borrowck/src/lib.rs:115 mir_borrowck
function mir_borrowck(tcx: TyCtxt, def: LocalDefId): Result<Map<LocalDefId, DefinitionSiteHiddenType>, ErrorGuaranteed> {
  assert(!tcx.is_typeck_child(LocalDefId.to_def_id(def)), "assertion failed: !tcx.is_typeck_child(def.to_def_id())");
  if (tcx.is_trivial_const(def)) {
    // debug!("Skipping borrowck because of trivial const");
    const opaque_types = new Map<LocalDefId, DefinitionSiteHiddenType>();
    return Ok(opaque_types);
  }
  const [input_body_steal] = tcx.mir_promoted(def);
  // debug!("run query mir_borrowck: {}", tcx.def_path_str(def));

  // We should eagerly check stalled coroutine obligations from HIR typeck.
  // Not doing so leads to silent normalization failures later, which will
  // fail to register opaque types in the next solver.
  const r = tcx.ensure_result().check_coroutine_obligations(def);
  if (r.$ === "Err") return r;

  const input_body: Body = input_body_steal.borrow();
  const guar = input_body.tainted_by_errors;
  if (guar !== undefined) {
    // debug!("Skipping borrowck because of tainted body");
    return Err(guar);
  } else if (input_body.should_skip()) {
    // debug!("Skipping borrowck because of injected body");
    const opaque_types = new Map<LocalDefId, DefinitionSiteHiddenType>();
    return Ok(opaque_types);
  } else {
    // PORT: `let tainted_by_errors = Default::default()` (a `Cell<Option<ErrorGuaranteed>>` lent to the root context)
    // is the root context's own field (root_cx.ts header): `finalize` reads it back.
    const tainted_by_errors: ErrorGuaranteed | undefined = undefined;
    const root_cx = BorrowCheckRootCtxt.new(tcx, def, undefined, tainted_by_errors);
    root_cx.do_mir_borrowck();
    return root_cx.finalize();
  }
}

