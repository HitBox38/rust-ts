/// Creates a `mir::Body` with a few disconnected basic blocks.
///
/// This is the `Body` that will be used by the `MockAnalysis` below. The shape of its CFG is not
/// important.
// rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:15 mock_body
function mock_body(): Body {
  const source_info = SourceInfo.outermost(DUMMY_SP);

  const blocks: BasicBlockData[] = [];
  const block = (n: number, kind: TerminatorKind): void => {
    const nop = Statement.new(source_info, StatementKind.Nop);

    blocks.push(BasicBlockData.new_stmts(Array.from({ length: n }, () => clone_Statement(nop)), new Terminator(clone_SourceInfo(source_info), kind), false));
  };

  const dummy_place = new Place(RETURN_PLACE, RawList.empty());

  block(4, TerminatorKind.Return);
  block(1, TerminatorKind.Return);
  block(2, {
    $: "Call",
    func: { $: "Copy", _0: clone_Place(dummy_place) },
    args: [],
    destination: clone_Place(dummy_place),
    target: START_BLOCK,
    unwind: UnwindAction.Continue,
    call_source: "Misc",
    fn_span: DUMMY_SP,
  });
  block(3, TerminatorKind.Return);
  block(0, TerminatorKind.Return);
  block(4, {
    $: "Call",
    func: { $: "Copy", _0: clone_Place(dummy_place) },
    args: [],
    destination: clone_Place(dummy_place),
    target: START_BLOCK,
    unwind: UnwindAction.Continue,
    call_source: "Misc",
    fn_span: DUMMY_SP,
  });

  return Body.new_cfg_only(blocks);
}

/// A dataflow analysis whose state is unique at every possible `SeekTarget`.
///
/// Uniqueness is achieved by having a *locally* unique effect before and after each statement and
/// terminator (see `effect_at_target`) while ensuring that the entry set for each block is
/// *globally* unique (see `mock_entry_set`).
///
/// For example, a `BasicBlock` with ID `2` and a `Call` terminator has the following state at each
/// location ("+x" indicates that "x" is added to the state).
///
/// | Location               | Before            | After  |
/// |------------------------|-------------------|--------|
/// | (on_entry)             | {102}             |        |
/// | statement 0            | +0                | +1     |
/// | statement 1            | +2                | +3     |
/// | `Call` terminator      | +4                | +5     |
/// | (on unwind)            | {102,0,1,2,3,4,5} |        |
///
/// The `102` in the block's entry set is derived from the basic block index and ensures that the
/// expected state is unique across all basic blocks. Remember, it is generated by
/// `mock_entry_states`, not from actually running `MockAnalysis` to fixpoint.
class MockAnalysis extends AnalysisBase<DenseBitSet<number>> {
  static readonly BASIC_BLOCK_OFFSET: number = 100;

  readonly Domain: Domain<DenseBitSet<number>> = Domain_DenseBitSet(DebugWithContext_impl<number, unknown>((a, b) => a === b, debug_int));
  readonly NAME = "mock";

  constructor(
    public body: Body,
    // dir: PhantomData<D>
    override readonly Direction: Direction,
  ) {
    super();
  }

  /// The entry set for each `BasicBlock` is the ID of that block offset by a fixed amount to
  /// avoid colliding with the statement/terminator effects.
  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:93 mock_entry_set
  mock_entry_set(bb: BasicBlock): DenseBitSet<number> {
    const ret = this.bottom_value(this.body);
    ret.insert(MockAnalysis.BASIC_BLOCK_OFFSET + BasicBlock.index(bb));
    return ret;
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:99 mock_entry_states
  mock_entry_states(): DenseBitSet<number>[] {
    const empty = this.bottom_value(this.body);
    const ret: DenseBitSet<number>[] = [];
    for (let i = 0; i < this.body.basic_blocks.deref().length; i++) ret.push(empty.clone());

    for (let bb = 0 as BasicBlock; bb < this.body.basic_blocks.deref().length; bb = (bb + 1) as BasicBlock) {
      ret[bb] = this.mock_entry_set(bb);
    }

    return ret;
  }

  /// Returns the index that should be added to the dataflow state at the given target.
  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:111 effect
  effect(loc: EffectIndex): number {
    let idx: number;
    switch (loc.effect) {
      case "Early":
        idx = loc.statement_index * 2;
        break;
      case "Primary":
        idx = loc.statement_index * 2 + 1;
        break;
    }

    assert(idx < MockAnalysis.BASIC_BLOCK_OFFSET, "Too many statements in basic block");
    return idx;
  }

  /// Returns the expected state at the given `SeekTarget`.
  ///
  /// This is the union of index of the target basic block, the index assigned to the
  /// target statement or terminator, and the indices of all preceding statements in the target
  /// basic block.
  ///
  /// For example, the expected state when calling
  /// `seek_before_primary_effect(Location { block: 2, statement_index: 2 })`
  /// would be `[102, 0, 1, 2, 3, 4]`.
  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:130 expected_state_at_target
  expected_state_at_target(target: SeekTarget): DenseBitSet<number> {
    const block = SeekTarget.block(target);
    const ret = this.bottom_value(this.body);
    ret.insert(MockAnalysis.BASIC_BLOCK_OFFSET + BasicBlock.index(block));

    let target_: EffectIndex;
    switch (target.$) {
      case "BlockEntry":
        return ret;
      case "Early":
        target_ = Effect.at_index(Effect.Early, target._0.statement_index);
        break;
      case "After":
        target_ = Effect.at_index(Effect.Primary, target._0.statement_index);
        break;
    }

    let pos = this.Direction.first_index(this.body.index(block));

    for (;;) {
      ret.insert(this.effect(pos));

      if (EffectIndex_eq(pos, target_)) {
        return ret;
      }

      pos = this.Direction.next_index(pos);
    }
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:161 bottom_value
  bottom_value(body: Body): DenseBitSet<number> {
    return DenseBitSet.new_empty(MockAnalysis.BASIC_BLOCK_OFFSET + body.basic_blocks.deref().length);
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:165 initialize_start_block
  initialize_start_block(_body: Body, _state: DenseBitSet<number>): void {
    panic("not implemented: This is never called since `MockAnalysis` is never iterated to fixpoint");
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:169 apply_early_statement_effect
  override apply_early_statement_effect(state: DenseBitSet<number>, _statement: Statement, location: Location): void {
    const idx = this.effect(Effect.at_index(Effect.Early, location.statement_index));
    assert(state.insert(idx), "assertion failed: state.insert(idx)");
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:179 apply_primary_statement_effect
  apply_primary_statement_effect(state: DenseBitSet<number>, _statement: Statement, location: Location): void {
    const idx = this.effect(Effect.at_index(Effect.Primary, location.statement_index));
    assert(state.insert(idx), "assertion failed: state.insert(idx)");
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:189 apply_early_terminator_effect
  override apply_early_terminator_effect(state: DenseBitSet<number>, _terminator: Terminator, location: Location): void {
    const idx = this.effect(Effect.at_index(Effect.Early, location.statement_index));
    assert(state.insert(idx), "assertion failed: state.insert(idx)");
  }

  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:199 apply_primary_terminator_effect
  override apply_primary_terminator_effect(state: DenseBitSet<number>, _terminator: Terminator, location: Location): void {
    const idx = this.effect(Effect.at_index(Effect.Primary, location.statement_index));
    assert(state.insert(idx), "assertion failed: state.insert(idx)");
  }
}

// #[derive(Clone, Copy, Debug, PartialEq, Eq)]
type SeekTarget = { $: "BlockEntry"; _0: BasicBlock } | { $: "Early"; _0: Location } | { $: "After"; _0: Location };

const SeekTarget = {
  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:218 block
  block(self: SeekTarget): BasicBlock {
    switch (self.$) {
      case "BlockEntry":
        return self._0;
      case "Early":
      case "After":
        return self._0.block;
    }
  },

  /// An iterator over all possible `SeekTarget`s in a given block in order, starting with
  /// `BlockEntry`.
  // rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:229 iter_in_block
  iter_in_block(body: Body, block: BasicBlock): SeekTarget[] {
    const statements_and_terminator: SeekTarget[] = [];
    for (let i = 0; i <= body.index(block).statements.length; i++) {
      for (let kind = 0; kind < 2; kind++) {
        const loc: Location = new Location(block, i);
        switch (kind) {
          case 0:
            statements_and_terminator.push({ $: "Early", _0: loc });
            break;
          case 1:
            statements_and_terminator.push({ $: "After", _0: loc });
            break;
          default:
            panic("internal error: entered unreachable code");
        }
      }
    }

    return [{ $: "BlockEntry", _0: block } as SeekTarget].concat(statements_and_terminator);
  },
};

const debug_SeekTarget = (t: SeekTarget): string =>
  t.$ === "BlockEntry" ? `BlockEntry(bb${t._0})` : `${t.$}(bb${t._0.block}[${t._0.statement_index}])`;

// rustc: compiler/rustc_mir_dataflow/src/framework/tests.rs:245 test_cursor
function test_cursor(analysis: MockAnalysis): void {
  const body = analysis.body;

  const cursor = new Results(analysis, analysis.mock_entry_states()).into_results_cursor(body);

  cursor.allow_unreachable();

  const every_target = (): SeekTarget[] => {
    const out: SeekTarget[] = [];
    for (let bb = 0 as BasicBlock; bb < body.basic_blocks.deref().length; bb = (bb + 1) as BasicBlock) {
      out.push(...SeekTarget.iter_in_block(body, bb));
    }
    return out;
  };

  const seek_to_target = (targ: SeekTarget): void => {
    switch (targ.$) {
      case "BlockEntry":
        cursor.seek_to_block_entry(targ._0);
        break;
      case "Early":
        cursor.seek_before_primary_effect(targ._0);
        break;
      case "After":
        cursor.seek_after_primary_effect(targ._0);
        break;
    }

    const expected = cursor.analysis().expected_state_at_target(targ);
    if (!DenseBitSet_eq(cursor.get(), expected)) {
      // assert_eq!(cursor.get(), &cursor.analysis().expected_state_at_target(targ));
      expect(`${debug_SeekTarget(targ)}: ${[...cursor.get().iter()]}`).toBe(`${debug_SeekTarget(targ)}: ${[...expected.iter()]}`);
    }
  };

  // Seek *to* every possible `SeekTarget` *from* every possible `SeekTarget`.
  //
  // By resetting the cursor to `from` each time it changes, we end up checking some edges twice.
  // What we really want is an Eulerian cycle for the complete digraph over all possible
  // `SeekTarget`s, but it's not worth spending the time to compute it.
  for (const from of every_target()) {
    seek_to_target(from);

    for (const to of every_target()) {
      // dbg!(from);
      // dbg!(to);
      seek_to_target(to);
      seek_to_target(from);
    }
  }
}

