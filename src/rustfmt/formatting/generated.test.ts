// Unit test for src/rustfmt/formatting/generated.ts (lane rustfmt-contract-3). generated.rs has no `#[cfg(test)]` tests
// upstream (no `// rustc:` markers); this checks the port against generated.rs's logic.
import { expect, test } from "bun:test";
import type { Config } from "../config/mod.ts";
import { is_generated_file } from "./generated.ts";

/** Only the option `is_generated_file` reads (`generated_marker_line_search_limit`, default 5). */
const config_with_limit = (n: number) => ({ generated_marker_line_search_limit: () => n }) as unknown as Config;

test("is_generated_file looks for `@generated` in the first `generated_marker_line_search_limit` lines", () => {
  const src = "// one\n// two\n// @generated by a tool\nfn main() {}\n";
  expect(is_generated_file(src, config_with_limit(5))).toBe(true);
  expect(is_generated_file(src, config_with_limit(3))).toBe(true);
  expect(is_generated_file(src, config_with_limit(2))).toBe(false);
  expect(is_generated_file(src, config_with_limit(0))).toBe(false);
  expect(is_generated_file("fn main() {}\r\n// x @generated\r\n", config_with_limit(5))).toBe(true);
  expect(is_generated_file("", config_with_limit(5))).toBe(false);
});
