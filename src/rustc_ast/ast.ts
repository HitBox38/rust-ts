// Succeeds if the path has a single segment that is arg-free and matches the given symbol.
// rustc: compiler/rustc_ast/src/ast.rs:103 eq
gen.Path.prototype.eq_Symbol = function (this: Path, name: Symbol): boolean {
  if (this.segments.length === 1 && this.segments[0]!.eq_Symbol(name)) {
    return true;
  } else {
    return false;
  }
};

// Succeeds if the path has segments that are arg-free and match the given symbols.
// rustc: compiler/rustc_ast/src/ast.rs:117 eq
gen.Path.prototype.eq_slice = function (this: Path, names: readonly Symbol[]): boolean {
  // PORT: `Iterator::eq` (same length, pairwise `PathSegment == Symbol`).
  if (this.segments.length !== names.length) {
    return false;
  }
  for (let i = 0; i < names.length; i++) {
    if (!this.segments[i]!.eq_Symbol(names[i]!)) {
      return false;
    }
  }
  return true;
};

