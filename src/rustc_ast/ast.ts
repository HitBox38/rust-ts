//! The Rust abstract syntax tree module.
//!
//! This module contains common structures forming the language AST.
//! Two main entities in the module are [`Item`] (which represents an AST element with
//! additional metadata), and [`ItemKind`] (which represents a concrete type and contains
//! information specific to the type of the item).
//!
//! Other module items worth mentioning:
//! - [`Ty`] and [`TyKind`]: A parsed Rust type.
//! - [`Expr`] and [`ExprKind`]: A parsed Rust expression.
//! - [`Pat`] and [`PatKind`]: A parsed Rust pattern. Patterns are often dual to expressions.
//! - [`Stmt`] and [`StmtKind`]: An executable action that does not return a value.
//! - [`FnDecl`], [`FnHeader`] and [`Param`]: Metadata associated with a function declaration.
//! - [`Generics`], [`GenericParam`], [`WhereClause`]: Metadata associated with generic parameters.
//! - [`EnumDef`] and [`Variant`]: Enum declaration.
//! - [`MetaItemLit`] and [`LitKind`]: Literal expressions.
//! - [`MacroDef`], [`MacStmtStyle`], [`MacCall`]: Macro definition and invocation.
//! - [`Attribute`]: Metadata associated with item.
//! - [`UnOp`], [`BinOp`], and [`BinOpKind`]: Unary and binary operators.
//
// Types and derived Debug impls are generated into ast.gen.ts (tools/codegen/types.ts).
//
// PORT: method placement (PORTING §8; the token.ts pattern).
// - Enum methods live on the companion const. Where ast.gen.ts has one (enums with unit variants)
//   it is re-defined here as `{ ...gen.X, fns }`; otherwise the companion is defined here. This is
//   safe at init: ast.gen.ts is only entered through this module.
// - Structs with inherent fns are generated classes (auto_class). Their static fns and associated
//   consts are assigned onto the generated class, which is re-exported as
//   `export const X = gen.X as typeof gen.X & {...}` plus `export type X = gen.X`. Their `&self`
//   methods are attached to the prototype and declared via `declare module "./ast.gen.ts"`.
// - Associated consts of data-only structs (`TraitBoundModifiers::NONE`, `ConstBlockItem::IDENT`)
//   live on a companion const of the same name.
// - `impl From<A> for B` -> `B.from_A(a)`, `impl TryFrom<A> for B` -> `B.try_from_A(a)`
//   (the rustc_error_messages convention); `impl PartialEq<A> for B` -> `b.eq_A(a)`;
//   `impl Display for X` -> `display_X(v): string` (as in rustc_span).
// - `impl Item<AssocItemKind>` (a second inherent impl of the generic `Item`) -> the `AssocItem`
//   companion const (`AssocItem.opt_generics(item)`): one prototype cannot hold both `opt_generics`.
// - `Box<T>` is `T`, so `impl From<Box<T>> for T` returns its argument.
// - Copy types (`FnHeader`, `Ident`, ...) are shared, not copied: treat them as immutable.
// - Derived `Clone` of AST nodes is not generated by tools/codegen yet; each `.clone()` of one is
//   `derive_clone("<type>")` at the exact call site, which is `unported`.
// - `&mut T` results are `MutRef<T>` views onto the field (rustc_span hygiene.ts).
