//! Validity checking for weak lang items
import { LangItem, type LanguageItems } from "../rustc_attr_ir/lang_items.ts";
import { WEAK_LANG_ITEMS } from "../rustc_attr_ir/weak_lang_items.ts";
import { required } from "../rustc_middle/middle/lang_items.ts";
import type { TyCtxt } from "../rustc_middle/ty/context.ts";
import { MissingLangItem_diagnostic, MissingPanicHandler_diagnostic, PanicUnwindWithoutStd_diagnostic } from "./diagnostics.ts";

/// Checks the crate for usage of weak lang items. Erroring on all the
/// lang items required by this crate, but not defined yet.
// rustc: compiler/rustc_passes/src/weak_lang_items.rs:14 check_crate
export function check_crate(tcx: TyCtxt, items: LanguageItems): void {
  // This is never called by user code, it's generated by the compiler. It
  // will never implicitly be added to the `missing` array unless we do so
  // here.
  if (items.eh_personality() === undefined) {
    items.missing.push(LangItem.EhPersonality);
  }

  items.trim_missing();

  verify(tcx, items);
}

// rustc: compiler/rustc_passes/src/weak_lang_items.rs:27 verify
function verify(tcx: TyCtxt, items: LanguageItems): void {
  // We only need to check for the presence of weak lang items if we're
  // emitting something that's not an rlib.
  const needs_check = tcx.crate_types().some((kind) => {
    switch (kind) {
      case "Dylib":
      case "ProcMacro":
      case "Cdylib":
      case "Executable":
      case "StaticLib":
      case "Sdylib":
        return true;
      case "Rlib":
        return false;
    }
  });
  if (!needs_check) {
    return;
  }

  // PORT: `FxHashSet<LangItem>` is only probed with `contains`, so its iteration order does not matter.
  const missing = new Set<LangItem>();
  for (const cnum of tcx.crates(null)) {
    for (const item of tcx.missing_lang_items(cnum)) {
      missing.add(item);
    }
  }

  for (const item of WEAK_LANG_ITEMS) {
    if (missing.has(item) && required(tcx, item) && items.get(item) === undefined) {
      if (item === LangItem.PanicImpl) {
        tcx.dcx().emit_err(MissingPanicHandler_diagnostic({}));
      } else if (item === LangItem.EhPersonality) {
        tcx.dcx().emit_err(PanicUnwindWithoutStd_diagnostic({}));
      } else {
        tcx.dcx().emit_err(MissingLangItem_diagnostic({ name: LangItem.name(item) }));
      }
    }
  }
}
