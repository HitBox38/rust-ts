// Unit tests of the pure parts of scripts/tools-src.ts (scripts/lib/tools-src.ts; plan-m8 D3, lane tools-prep-m8): UPSTREAM.json's
// cargo pin, and the check that the tools-deps workspace's pruned lock resolved nothing away from the root lock.
import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { TOOLS_DEPS_MEMBERS, TOOLS_DEPS_PACKAGES, cargoPinOf, cargoSrcDir, cargoTarballUrl, lockPackages, lockSubsetErrors, toolsDepsManifest } from "./tools-src.ts";
import { REPO_ROOT } from "./upstream-root.ts"; // not common.ts: see scripts/lib/upstream-root.ts

describe("UPSTREAM.json cargo", () => {
  test("the repo's pin is plan-m8 D3's, and the gitlink's commit", () => {
    const p = cargoPinOf(JSON.parse(readFileSync(join(REPO_ROOT, "UPSTREAM.json"), "utf8")));
    expect(p).toEqual({ repo: "https://github.com/rust-lang/cargo.git", commit: "29c5daa1afc262323364e039bb70c83372cc702c", sha256: "a1aaf1613ebbf43f5234626f589350d64ea3d4c1a889bce8f55562a86404ad16" });
    if (typeof p === "string") return;
    expect(cargoTarballUrl(p)).toBe("https://codeload.github.com/rust-lang/cargo/tar.gz/29c5daa1afc262323364e039bb70c83372cc702c");
    expect(cargoSrcDir("/d/cargo-src", p)).toBe("/d/cargo-src/cargo-29c5daa1afc262323364e039bb70c83372cc702c");
  });
  test("a missing pin, another repo, a short commit, a bad hash: refused", () => {
    const ok = { repo: "https://github.com/rust-lang/cargo.git", commit: "a".repeat(40), sha256: "b".repeat(64) };
    expect(cargoPinOf({})).toContain("has no cargo");
    expect(cargoPinOf({ cargo: { ...ok, repo: "https://example.com/cargo.git" } })).toContain("cargo.repo");
    expect(cargoPinOf({ cargo: { ...ok, commit: "29c5daa1a" } })).toContain("not a full commit hash");
    expect(cargoPinOf({ cargo: { ...ok, sha256: "B".repeat(64) } })).toContain("not a SHA-256");
    expect(cargoPinOf({ cargo: ok })).toEqual(ok);
  });
});

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "clippy_config"
version = "0.1.101"
dependencies = [
 "toml",
]

[[package]]
name = "toml"
version = "1.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${"1".repeat(64)}"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.228"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${"2".repeat(64)}"
`;

describe("the tools-deps lock", () => {
  test("lockPackages: name, version, and source and checksum when there are", () => {
    expect(lockPackages(LOCK)).toEqual([
      { name: "clippy_config", version: "0.1.101" },
      { name: "toml", version: "1.1.0", source: "registry+https://github.com/rust-lang/crates.io-index", checksum: "1".repeat(64) },
      { name: "serde", version: "1.0.228", source: "registry+https://github.com/rust-lang/crates.io-index", checksum: "2".repeat(64) },
    ]);
  });
  test("a pruned lock is a subset; its dependencies lists may differ", () => {
    const pruned = LOCK.replace(/\[\[package\]\]\nname = "serde"[^]*$/, "").replace(' "serde",\n', "");
    expect(lockPackages(pruned).map((p) => p.name)).toEqual(["clippy_config", "toml"]);
    expect(lockSubsetErrors(pruned, LOCK)).toEqual([]);
  });
  test("another version, another checksum, a new package: each refused", () => {
    expect(lockSubsetErrors(LOCK.replace('version = "1.1.0"', 'version = "1.1.1"'), LOCK)).toEqual(["toml 1.1.1 (registry+https://github.com/rust-lang/crates.io-index) is not in the root Cargo.lock with that source and checksum"]);
    expect(lockSubsetErrors(LOCK.replace("1".repeat(64), "3".repeat(64)), LOCK)).toHaveLength(1);
    expect(lockSubsetErrors(`${LOCK}\n[[package]]\nname = "x"\nversion = "1.0.0"\n`, LOCK)).toEqual(["x 1.0.0 (path) is not in the root Cargo.lock with that source and checksum"]);
  });
  test("the workspace: its members, and the packages they reach by path", () => {
    expect(TOOLS_DEPS_MEMBERS.every((m) => TOOLS_DEPS_PACKAGES.includes(m))).toBe(true);
    expect(toolsDepsManifest()).toContain('members = ["src/tools/clippy/clippy_config", "src/tools/rustfmt"]');
    expect(toolsDepsManifest()).toContain('resolver = "2"');
  });
});
