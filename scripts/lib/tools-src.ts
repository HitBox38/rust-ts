/** UPSTREAM.json `cargo`: cargo's repository, the commit the pin's `src/tools/cargo` gitlink records, and its tarball's SHA-256. */
export interface CargoPin {
  repo: string;
  commit: string;
  sha256: string;
}

/** UPSTREAM.json `cargo`, checked, or an error message. */
export function cargoPinOf(upstreamJson: unknown): CargoPin | string {
  const c = (upstreamJson as { cargo?: Partial<CargoPin> } | undefined)?.cargo;
  if (c === undefined) return "UPSTREAM.json has no cargo { repo, commit, sha256 } (plan-m8 D3)";
  if (c.repo !== "https://github.com/rust-lang/cargo.git") return `UPSTREAM.json cargo.repo ${JSON.stringify(c.repo)} is not https://github.com/rust-lang/cargo.git`;
  if (typeof c.commit !== "string" || !/^[0-9a-f]{40}$/.test(c.commit)) return `UPSTREAM.json cargo.commit ${JSON.stringify(c.commit)} is not a full commit hash`;
  if (typeof c.sha256 !== "string" || !/^[0-9a-f]{64}$/.test(c.sha256)) return `UPSTREAM.json cargo.sha256 ${JSON.stringify(c.sha256)} is not a SHA-256`;
  return { repo: c.repo, commit: c.commit, sha256: c.sha256 };
}

/** GitHub's tarball of the commit (the URL the plan measured the SHA-256 of). */
export const cargoTarballUrl = (p: CargoPin): string => `https://codeload.github.com/rust-lang/cargo/tar.gz/${p.commit}`;

/** The directory GitHub's tarball unpacks to, under `root` (`$RUST_TS_DATA/cargo-src`). */
export const cargoSrcDir = (root: string, p: CargoPin): string => join(root, `cargo-${p.commit}`);

