/** A `[[package]]` of a Cargo.lock: what identifies it (its `dependencies` list depends on the features the workspace asks for). */
export interface LockPackage {
  name: string;
  version: string;
  source?: string;
  checksum?: string;
}

/** The `[[package]]` entries of a Cargo.lock. */
export function lockPackages(text: string): LockPackage[] {
  const out: LockPackage[] = [];
  for (const block of text.split(/^\[\[package\]\]\s*$/m).slice(1)) {
    const field = (k: string) => new RegExp(`^${k} = "([^"]*)"\\s*$`, "m").exec(block.split(/^\[/m)[0]!)?.[1];
    const name = field("name");
    const version = field("version");
    if (name === undefined || version === undefined) continue;
    const p: LockPackage = { name, version };
    const source = field("source");
    const checksum = field("checksum");
    if (source !== undefined) p.source = source;
    if (checksum !== undefined) p.checksum = checksum;
    out.push(p);
  }
  return out;
}

const lockKey = (p: LockPackage): string => `${p.name} ${p.version} ${p.source ?? "(path)"} ${p.checksum ?? "-"}`;

/**
 * The packages of `sub` (the scratch workspace's lock after cargo pruned it) that `full` (the rust checkout's root lock) does not
 * have with the same name, version, source and checksum: a new resolution, which must not happen. Empty when `sub` is a subset.
 */
export function lockSubsetErrors(sub: string, full: string): string[] {
  const have = new Set(lockPackages(full).map(lockKey));
  return lockPackages(sub)
    .filter((p) => !have.has(lockKey(p)))
    .map((p) => `${p.name} ${p.version} (${p.source ?? "path"}) is not in the root Cargo.lock with that source and checksum`);
}

/** A size in MiB, for the setup's report. */
export const mib = (bytes: number): string => `${(bytes / (1 << 20)).toFixed(1)} MiB`;
