// Generates harness/corpus/escape-synthetic/*.rs: quoted literals that drive
// rustc-literal-escaper through every `Mode` and every reachable `EscapeError` variant,
// plus edge cases the real corpus rarely contains (\u{} limits, surrogates, \x80 in str vs
// byte str, NUL in C strings, CRLF / line-continuation whitespace, raw strings with bare CR).
//
//   bun harness/corpus/gen-escape.ts      rewrite the files (output is deterministic; commit them)
//
// The files are token soup for the `escape-synthetic` suite (rustc_lexer + escaper), not valid
// Rust. Every literal is terminated (the probe skips unterminated ones). Control characters are
// written with the constants below so the generator itself stays readable.
//
// Not reachable from lexed source: `EscapeError::LoneSlash` (content ending in a lone `\`):
// rustc_lexer always consumes the character after a `\` inside quotes, so a terminated literal
// never ends with an unpaired `\`. See docs/handoff/harness-w2.md.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const TAB = "\t";
const LF = "\n";
const CR = "\r";
const NUL = "\u0000";
const NBSP = " ";
const EM_SPACE = " ";
const BOM = "﻿";

const HEADER = "// GENERATED by harness/corpus/gen-escape.ts; do not edit. Token soup, not valid Rust.";

/** Escape-sequence bodies shared by all quoted (non-raw) modes, valid or not. */
const ESCAPES = [
  // simple escapes
  "\\n", "\\r", "\\t", "\\\\", "\\0", "\\'", '\\"',
  // invalid escape characters
  "\\z", "\\N", "\\ ", "\\é", "\\U{41}", "\\a", "\\e", "\\x", "\\u",
  // \x: length, digits, range
  "\\x0", "\\x1", "\\xz1", "\\x1z", "\\xg0", "\\x00", "\\x41", "\\x7f", "\\x7F", "\\x80", "\\xFF", "\\xff", "\\x123",
  // \u: braces, digits, underscores, length, range, surrogates
  "\\u12", "\\u{", "\\u{}", "\\u{12", "\\u{zz}", "\\u{1z}", "\\u{_1}", "\\u{_}", "\\u{1_}", "\\u{1__2}", "\\u{0}",
  "\\u{41}", "\\u{aBcD}", "\\u{7F}", "\\u{80}", "\\u{FF}", "\\u{D7FF}", "\\u{D800}", "\\u{DBFF}", "\\u{DC00}",
  "\\u{DFFF}", "\\u{E000}", "\\u{FFFF}", "\\u{10000}", "\\u{10FFFF}", "\\u{10_FFFF}", "\\u{1_0_F_F_F_F}",
  "\\u{110000}", "\\u{FFFFFF}", "\\u{1000000}", "\\u{1234567}", "\\u{0000001}", "\\u{000000}", "\\u{00000041}",
  "\\u{1F600}", "\\u{ 41}", "\\u{41 }", "\\u{-1}", "\\u{+41}",
];

/** Bare (unescaped) characters with special meaning in some mode. */
const BARE = ["a", "é", "中", "😀", TAB, CR, NUL, "'", '"', "\u007f", "\u0080", "ÿ", "​", NBSP, BOM];

const files: Record<string, string[]> = {};

// ---- Char / Byte: one literal per line ------------------------------------------------------
for (const [name, prefix] of [["char", ""], ["byte", "b"]] as const) {
  const lits: string[] = [];
  for (const e of ESCAPES) lits.push(`${prefix}'${e}'`);
  for (const c of BARE) lits.push(`${prefix}'${c}'`);
  lits.push(
    `${prefix}''`, // ZeroChars
    `${prefix}'ab'`, // MoreThanOneChar
    `${prefix}'\\n\\n'`,
    `${prefix}'a\\n'`,
    `${prefix}'\\x41b'`,
    `${prefix}'\\u{41}\\u{42}'`,
    `${prefix}'é'`, // e + combining acute: two chars
    `${prefix}'👨‍👩'`, // ZWJ sequence
    `${prefix}'''`, // EscapeOnlyChar (bare quote)
    `${prefix}'${LF}'`, // literal newline
    `${prefix}'\\z\\z'`, // several errors, only the first is reported for single chars
    `${prefix}'\\u{D800}x'`,
    `${prefix}'a'suffix`,
    `${prefix}'a'u8`,
    `${prefix}'\\''_x`,
  );
  files[name] = lits;
}

// ---- Strings: each escape alone, then mixed with text and with each other ---------------------
for (const [name, prefix] of [["str", ""], ["byte_str", "b"], ["c_str", "c"]] as const) {
  const lits: string[] = [];
  for (const e of ESCAPES) lits.push(`${prefix}"${e}"`);
  // (a bare `"` would end the literal)
  for (const c of BARE.filter((c) => c !== '"')) lits.push(`${prefix}"${c}"`, `${prefix}"x${c}y"`);
  lits.push(
    `${prefix}""`,
    `${prefix}"abc"`,
    `${prefix}"a\\x80b\\xFFc"`, // OutOfRangeHexEscape in str, fine in byte/c str
    `${prefix}"\\u{0}\\x00\\0${NUL}"`, // NulInCStr four ways
    `${prefix}"\\z\\x80\\u{}\\u{D800}${CR}é\\0"`, // several errors in one literal, in order
    `${prefix}"${CR}${LF}"`, // CRLF in source (rustc normalizes before lexing; the escaper sees the CR)
    `${prefix}"a${CR}"`,
    `${prefix}"${TAB}${TAB}\\t"`,
    `${prefix}"\\\\\\\\\\"\\'"`,
    `${prefix}"'"`,
    `${prefix}"\\u{10FFFF}\\u{80}\\u{FF}é😀"`,
    `${prefix}"multi${LF}line${LF}"`,
    `${prefix}"a"suffix`,
    `${prefix}"a"_b`,
  );
  files[name] = lits;
}

// ---- Line continuations: `\` + newline skips ASCII whitespace -------------------------------
{
  const bodies = [
    `a\\${LF}b`,
    `a\\${LF}   b`,
    `a\\${LF}${TAB} ${TAB}b`,
    `a\\${LF}${LF}b`, // MultipleSkippedLinesWarning
    `a\\${LF}  ${LF}  b`, // MultipleSkippedLinesWarning
    `a\\${LF}${LF}${LF}${LF}b`,
    `a\\${LF}${NBSP}b`, // UnskippedWhitespaceWarning
    `a\\${LF}  ${EM_SPACE}b`, // UnskippedWhitespaceWarning
    `a\\${LF}\u0085b`, // NEL: Unicode whitespace, not ASCII
    `a\\${LF} b`,
    `a\\${LF}${CR}${LF}b`,
    `a\\${CR}${LF}b`, // backslash then CR: not a continuation
    `a\\${CR}b`,
    `a\\${LF}${CR}b`,
    `a\\${LF}\u000bb`, // vertical tab
    `a\\${LF}\u000cb`, // form feed
    `a\\${LF}`, // continuation at the end of the literal
    `\\${LF}`,
    `\\${LF}\\${LF}x`,
    `a\\${LF} \\${LF} b`,
    `a\\${LF}${NBSP}${LF}b`,
    `a\\${LF}\\z`,
    `a\\${LF}${NUL}`,
    `a\\${LF}\\${LF}${LF}${NBSP}b`,
  ];
  const lits: string[] = [];
  for (const prefix of ["", "b", "c"]) for (const body of bodies) lits.push(`${prefix}"${body}"`);
  // In char literals a continuation is an invalid escape (`\` + newline).
  lits.push(`'\\${LF}'`, `b'\\${LF}'`);
  files["continuation"] = lits;
}

// ---- Raw strings: no escapes; bare CR is an error; bytes must be ASCII; no NUL in C strings ---
{
  const bodies = ["", "abc", "\\n\\x80\\u{0}\\", '"', `a${CR}b`, `${CR}${LF}`, `${CR}`, `x${CR}${CR}`, `é`, `\u0080`, `${NUL}`, `a${NUL}${CR}é`, TAB, `${LF}${LF}`, `\\${LF}  b`, `😀`, `\\0`];
  const lits: string[] = [];
  for (const prefix of ["r", "br", "cr"]) {
    for (const body of bodies) {
      const hashes = body.includes('"') ? "#" : "";
      lits.push(`${prefix}${hashes}"${body}"${hashes}`);
    }
    lits.push(`${prefix}##"a"#b${CR}"##`, `${prefix}###"${NUL}"###`, `${prefix}"a"suffix`);
  }
  files["raw"] = lits;
}

// ---- Whole-file shapes: shebang, BOM, CRLF line endings, literals among other tokens ---------
files["crlf"] = [
  `fn main() {`,
  `    let a = "line one${CR}${LF}line two";`,
  `    let b = "cont\\${CR}${LF}    tinued";`,
  `    let c = b"x\\${LF}  ${CR}${LF}y";`,
  `    let d = r"raw${CR}${LF}raw";`,
  `    let e = c"nul\\0${CR}${LF}";`,
  `    let f = '${CR}';`,
  `}`,
].map((l) => l + CR); // CRLF endings (joined with LF below)
files["shebang"] = [`#!/usr/bin/env run-cargo-script`, `fn main() { let _ = ("\\x80", b"\\x80", c"\\x80", '\\u{D800}', b'\\xFF'); }`];
files["bom"] = [`${BOM}fn main() { let _ = ["${BOM}", "\\u{FEFF}", b"${BOM}"]; }`];
files["mixed"] = [
  `fn f<'a>(x: &'a str) -> char { 'x' }`,
  `macro_rules! m { ($e:expr) => { ($e, '\\'', "\\"") } }`,
  `const S: &[u8] = b"\\x00\\x7f\\x80\\xff"; const C: &core::ffi::CStr = c"\\u{7f}\\u{80}";`,
  `static T: [char; 3] = ['\\u{10FFFF}', '\\u{110000}', '\\u{_10}'];`,
  `let s = r#"has "quotes" and \\x80"#; let t = br##"#"##; let u = cr#"\\0"#;`,
  `/* 'not' "a" b'literal' */ // "nor" 'this'`,
  `let lt = 'static; let lab = 'outer: loop {}; let ch = 'o';`,
];

const OUT = join(import.meta.dir, "escape-synthetic");
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const [name, lines] of Object.entries(files)) {
  const shebang = name === "shebang" || name === "bom";
  const body = (shebang ? lines : [HEADER, ...lines]).join(LF) + LF;
  writeFileSync(join(OUT, `${name}.rs`), body);
}
console.log(`wrote ${readdirSync(OUT).length} files to ${OUT}`);
