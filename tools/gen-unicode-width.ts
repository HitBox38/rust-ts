// Generates the unicode-width (=0.2.2) lookup tables from the oracle (the `uwidth` probe), so
// the port uses exactly the widths of the crate version rustc_span depends on.
//   bun tools/gen-unicode-width.ts
//
// Layout mirrors upstream's `tables.rs` (scripts/unicode.py `make_tables`): a three-level trie
//   WIDTH_ROOT[cp >> 13]            -> sub-table index into WIDTH_MIDDLE   (256 entries)
//   WIDTH_MIDDLE[t1][cp >> 7 & 0x3F] -> sub-table index into WIDTH_LEAVES  (64 entries each)
//   WIDTH_LEAVES[t2][cp >> 2 & 0x1F] -> 4 packed 2-bit widths per byte      (32 bytes each)
// with a separate root for the `cjk` widths and shared, deduplicated middle/leaf tables.
//
// Differences from upstream's data (see the PORT note in the output): upstream stores the code 3
// for characters that need special handling in *string* width (ligatures, emoji presentation...)
// and resolves them in `lookup_width`'s match. The probe only observes per-char widths, so here
// a leaf entry holds the char's width directly; only width 3 (U+17D8) uses the code 3, which
// `lookup_width` resolves to `(3, WidthInfo::DEFAULT)` exactly as upstream does.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO, die, run } from "../scripts/lib/common.ts";
import { probePath } from "../scripts/probes.ts";

const r = await run([probePath("uwidth")]);
if (r.code !== 0) die(`uwidth failed: ${r.stderr}`);
const data = JSON.parse(r.stdout) as { unicode_version: string; width: [number, number, number][]; width_cjk: [number, number, number][] };

const MAX = 0x110000;

/** Per code point 2-bit code. `None` (control chars < U+00A0, never looked up) and surrogates
 *  (not scalar values) get 0; `single_char_width` never consults the tables for them. */
function codes(runs: [number, number, number][]): Uint8Array {
  const out = new Uint8Array(MAX);
  for (const [lo, hi, w] of runs) {
    if (w > 3) die(`width ${w} does not fit in 2 bits`);
    if (w < 0) continue;
    if (w === 3 && !(lo === 0x17d8 && hi === 0x17d8)) die(`unexpected width 3 at ${lo.toString(16)}`);
    out.fill(w, lo, hi + 1);
  }
  return out;
}

const leaves: Uint8Array[] = [];
const leafIdx = new Map<string, number>();
const middles: Uint8Array[] = [];
const middleIdx = new Map<string, number>();

function intern(list: Uint8Array[], idx: Map<string, number>, t: Uint8Array): number {
  const k = t.join(",");
  let i = idx.get(k);
  if (i === undefined) {
    i = list.length;
    if (i > 255) die("sub-table index does not fit in u8");
    list.push(t);
    idx.set(k, i);
  }
  return i;
}

function root(c: Uint8Array): Uint8Array {
  const rootT = new Uint8Array(256);
  for (let r1 = 0; r1 < 256; r1++) {
    const mid = new Uint8Array(64);
    for (let m = 0; m < 64; m++) {
      const leaf = new Uint8Array(32);
      for (let b = 0; b < 32; b++) {
        let byte = 0;
        for (let k = 0; k < 4; k++) {
          const cp = (r1 << 13) | (m << 7) | (b << 2) | k;
          byte |= (cp < MAX ? c[cp]! : 0) << (2 * k);
        }
        leaf[b] = byte;
      }
      mid[m] = intern(leaves, leafIdx, leaf);
    }
    rootT[r1] = intern(middles, middleIdx, mid);
  }
  return rootT;
}

const widthRoot = root(codes(data.width));
const widthRootCjk = root(codes(data.width_cjk));

function bytes(t: Uint8Array, indent: string): string {
  const lines: string[] = [];
  for (let i = 0; i < t.length; i += 32) lines.push(indent + Array.from(t.subarray(i, i + 32)).join(",") + ",");
  return lines.join("\n");
}
function nested(name: string, list: Uint8Array[]): string {
  return `export const ${name}: readonly Uint8Array[] = [\n${list.map((t) => `  new Uint8Array([\n${bytes(t, "    ")}\n  ]),`).join("\n")}\n];\n`;
}

const m = /^\((\d+), (\d+), (\d+)\)$/.exec(data.unicode_version);
if (!m) die(`bad unicode_version ${data.unicode_version}`);

let out = `// GENERATED by tools/gen-unicode-width.ts from the oracle (unicode-width =0.2.2, Unicode ${m[1]}.${m[2]}.${m[3]}). Do not edit.
// Three-level width trie with the layout of upstream's tables.rs (WIDTH_ROOT / WIDTH_ROOT_CJK /
// WIDTH_MIDDLE / WIDTH_LEAVES); see tools/gen-unicode-width.ts.
// PORT: leaf entries hold each char's width (derived from \`UnicodeWidthChar::width\` /
// \`width_cjk\`); only U+17D8 (width 3) uses code 3. Upstream also marks ligature/emoji chars
// with code 3 for string widths, which this data does not carry.

// crate: unicode-width-0.2.2/src/tables.rs:165 UNICODE_VERSION
/// The version of [Unicode](http://www.unicode.org/)
/// that this version of unicode-width is based on.
export const UNICODE_VERSION: readonly [number, number, number] = [${m[1]}, ${m[2]}, ${m[3]}];

export const WIDTH_ROOT = new Uint8Array([
${bytes(widthRoot, "  ")}
]);

export const WIDTH_ROOT_CJK = new Uint8Array([
${bytes(widthRootCjk, "  ")}
]);

`;
out += nested("WIDTH_MIDDLE", middles) + "\n" + nested("WIDTH_LEAVES", leaves);
const file = "src/vendor/unicode_width/tables.gen.ts";
writeFileSync(join(REPO, file), out);
console.log(`wrote ${file} (${middles.length} middle, ${leaves.length} leaf tables)`);
