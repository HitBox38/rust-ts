// Generates unicode lookup tables from the oracle (lexdump --unicode), so the port
// uses exactly the Unicode version of the pinned upstream dependencies.
//   bun tools/gen-unicode.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO, die, run } from "../scripts/lib/common.ts";
import { probePath } from "../scripts/probes.ts";

const r = await run([probePath("lexdump"), "--unicode"]);
if (r.code !== 0) die(`lexdump --unicode failed: ${r.stderr}`);
const data = JSON.parse(r.stdout) as Record<string, string | [number, number][]>;

function table(name: string, ranges: [number, number][]): string {
  const flat = ranges.flat();
  const lines: string[] = [];
  for (let i = 0; i < flat.length; i += 16) lines.push("  " + flat.slice(i, i + 16).join(",") + ",");
  return `export const ${name.toUpperCase()} = new Uint32Array([\n${lines.join("\n")}\n]);\n`;
}

function emit(file: string, header: string, names: string[]): void {
  let out = `// GENERATED by tools/gen-unicode.ts from the oracle (Unicode ${data.unicode_version}). Do not edit.\n// ${header}\n// Flat [start, end] inclusive code point ranges, sorted.\n\n`;
  for (const n of names) out += table(n, data[n] as [number, number][]) + "\n";
  writeFileSync(join(REPO, file), out);
  console.log(`wrote ${file}`);
}

emit("src/vendor/unicode_ident/tables.ts", "unicode-ident =1.0.24", ["xid_start", "xid_continue"]);
emit("src/vendor/unicode_properties/tables.ts", "unicode-properties =0.1.4 (emoji)", ["emoji_char"]);
emit("src/std/unicode/tables.ts", "core::char::escape_debug: chars printed as \\u{..}", ["debug_escape_unicode"]);
