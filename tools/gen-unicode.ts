// Generates unicode lookup tables from the oracle (lexdump --unicode), so the port
// uses exactly the Unicode version of the pinned upstream dependencies.
//   bun tools/gen-unicode.ts           write the tables
//   bun tools/gen-unicode.ts --check   compare the checked-in tables with the oracle (ERROR on drift)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO, die, run } from "../scripts/lib/common.ts";
import { probePath } from "../scripts/probes.ts";

const CHECK = process.argv.includes("--check");

const r = await run([probePath("lexdump"), "--unicode"]);
if (r.code !== 0) die(`lexdump --unicode failed: ${r.stderr}`);
const data = JSON.parse(r.stdout) as Record<string, string | number[][]>;

function rows(name: string, flat: number[], width: number): string {
  const lines: string[] = [];
  for (let i = 0; i < flat.length; i += width) lines.push("  " + flat.slice(i, i + width).join(",") + ",");
  return `export const ${name} = new Uint32Array([\n${lines.join("\n")}\n]);\n`;
}

/** [probe key, exported const name, kind]: `ranges` = flat [start, end] pairs; `mapping` = flat [cp, a, b, c] quads. */
type Table = [key: string, name: string, kind?: "ranges" | "mapping"];

function emit(version: string, header: string, tables: Table[]): string {
  let out = `// GENERATED by tools/gen-unicode.ts from the oracle (Unicode ${version}). Do not edit.\n// ${header}\n`;
  out += tables.some(([, , k]) => k === "mapping")
    ? "// Range tables: flat [start, end] inclusive code point ranges, sorted.\n// Mapping tables: flat [c, m0, m1, m2] quads sorted by c; c maps to m0 m1 m2 (0 = no char).\n\n"
    : "// Flat [start, end] inclusive code point ranges, sorted.\n\n";
  for (const [key, name, kind] of tables) {
    const v = data[key];
    if (!Array.isArray(v)) die(`lexdump --unicode has no '${key}' (rebuild it: bun scripts/probes.ts build lexdump)`);
    out += rows(name, v.flat(), 16) + "\n";
  }
  return out;
}

const FILES: [string, string][] = [
  [
    "src/vendor/unicode_ident/tables.ts",
    emit(data.unicode_version as string, "unicode-ident =1.0.24", [
      ["xid_start", "XID_START"],
      ["xid_continue", "XID_CONTINUE"],
    ]),
  ],
  [
    "src/vendor/unicode_properties/tables.ts",
    emit(data.unicode_version as string, "unicode-properties =0.1.4 (emoji)", [["emoji_char", "EMOJI_CHAR"]]),
  ],
  [
    "src/std/unicode/tables.ts",
    emit(data.core_unicode_version as string,
      "core (oracle toolchain): DEBUG_ESCAPE_UNICODE = chars `escape_debug` prints as \\u{..};\n" +
        "// the rest are the `char` methods of library/core/src/char/methods.rs evaluated by the oracle's core\n" +
        "// (`is_alphabetic`, `is_numeric`, `is_lowercase`, `is_uppercase`, `is_titlecase`, `is_case_ignorable`,\n" +
        "// `is_whitespace`, `to_lowercase`, `to_uppercase`), named after the core::unicode lookups they stand for.",
      [
        ["debug_escape_unicode", "DEBUG_ESCAPE_UNICODE"],
        ["alphabetic", "ALPHABETIC"],
        ["case_ignorable", "CASE_IGNORABLE"],
        ["lowercase", "LOWERCASE"],
        ["titlecase", "LT"],
        ["numeric", "N"],
        ["uppercase", "UPPERCASE"],
        ["white_space", "WHITE_SPACE"],
        ["to_lower", "TO_LOWER", "mapping"],
        ["to_upper", "TO_UPPER", "mapping"],
      ],
    ),
  ],
];

let drift = 0;
for (const [file, text] of FILES) {
  const path = join(REPO, file);
  if (CHECK) {
    let cur = "";
    try {
      cur = readFileSync(path, "utf8");
    } catch {}
    if (cur !== text) {
      console.log(`ERROR: ${file} differs from the oracle; run: bun tools/gen-unicode.ts`);
      drift++;
    } else console.log(`ok ${file}`);
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${file}`);
  }
}
if (drift) process.exit(1);
