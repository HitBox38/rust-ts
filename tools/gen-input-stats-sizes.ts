// Generates src/rustc_passes/input_stats_sizes.gen.ts from the output of the `nodesizes` probe (tools/probes/nodesizes):
// `size_of::<T>()` of every AST and HIR type rustc_passes input_stats.rs measures (`size_of_val(val)`), as the oracle
// compiler lays them out. These are Rust layout facts of the pinned compiler's own types, so they come from a probe
// linking that compiler's crates (rustc-dev), never from hand-typed numbers.
//   bun tools/gen-input-stats-sizes.ts            write the file (builds nothing: run `bun scripts/probes.ts build nodesizes` first)
//   bun tools/gen-input-stats-sizes.ts --check    exit 1 if the file is not what the probe prints now
// src/rustc_passes/input_stats_sizes.oracle.test.ts runs the same check as a unit test (so the gate requires the probe).
// The output parses strictly: one `<key> <size>` line per type, keys unique, nothing else.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PIN, REPO, die, parseArgs } from "../scripts/lib/common.ts";
import { probePath } from "../scripts/probes.ts";

export const GEN_FILE = join(REPO, "src", "rustc_passes", "input_stats_sizes.gen.ts");

/** The probe's stdout. */
export function probeOutput(): string {
  const r = Bun.spawnSync([probePath("nodesizes")], { stdout: "pipe", stderr: "pipe" });
  if (r.exitCode !== 0) die(`nodesizes exited ${r.exitCode}: ${r.stderr.toString().trim()}`);
  return r.stdout.toString();
}

/** The generated file's text for the probe output `out`; throws on anything unexpected. */
export function render(out: string): string {
  const lines = out.split("\n");
  if (lines.pop() !== "") throw new Error("nodesizes: output does not end with a newline");
  const seen = new Set<string>();
  const rows: string[] = [];
  for (const l of lines) {
    const m = /^([A-Za-z_:<>]+) (0|[1-9][0-9]*)$/.exec(l);
    if (m === null) throw new Error(`nodesizes: unexpected line ${JSON.stringify(l)}`);
    if (seen.has(m[1]!)) throw new Error(`nodesizes: duplicate key ${m[1]}`);
    seen.add(m[1]!);
    rows.push(`  ${JSON.stringify(m[1])}: ${m[2]},`);
  }
  if (rows.length === 0) throw new Error("nodesizes: no output");
  return [
    `// GENERATED by tools/gen-input-stats-sizes.ts from the output of tools/probes/nodesizes (rustc-dev of the pinned`,
    `// toolchain ${PIN.nightlyName}, ${PIN.commit.slice(0, 12)}). Do not edit; regenerate with \`bun tools/gen-input-stats-sizes.ts\`.`,
    `// \`size_of::<T>()\` of the AST and HIR types rustc_passes input_stats.rs measures, keyed as input_stats.ts names them`,
    `// (\`hir::Ty<AmbigArg>\` is visit_ty's \`hir::Ty<'v, AmbigArg>\`).`,
    `export const NODE_SIZES = {`,
    ...rows,
    `} as const;`,
    `export type NodeSizeKey = keyof typeof NODE_SIZES;`,
    ``,
  ].join("\n");
}

if (import.meta.main) {
  const args = parseArgs(process.argv.slice(2));
  const want = render(probeOutput());
  if (args.check) {
    const have = readFileSync(GEN_FILE, "utf8");
    if (have !== want) {
      console.log(`ERROR: ${GEN_FILE} is stale; run: bun tools/gen-input-stats-sizes.ts`);
      process.exit(1);
    }
    console.log(`${GEN_FILE}: up to date`);
  } else {
    writeFileSync(GEN_FILE, want);
    console.log(`wrote ${GEN_FILE}`);
  }
}
