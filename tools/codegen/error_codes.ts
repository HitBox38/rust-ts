// Error-code generator: reads the `error_codes!` list in compiler/rustc_error_codes/src/lib.rs (at
// the pin) and writes src/rustc_errors/error_codes.gen.ts with one `E<nnnn>` constant per code and
// the list of all codes, i.e. the constants half of `define_error_code_constants_and_diagnostics_table!`
// (compiler/rustc_errors/src/codes.rs). The long descriptions (`include_str!` of the `.md` files,
// ~1.3 MB) are not embedded; codes.ts keeps them lazy.
//
//   bun tools/codegen/error_codes.ts [--upstream <checkout>] [--out <file>]
//
// Exits 1 with an `ERROR:` line if the checkout is not at the pinned commit (UPSTREAM.json), or
// if the macro body cannot be found or is malformed.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function dataDir(): string {
  if (process.env["RUST_TS_DATA"]) return process.env["RUST_TS_DATA"];
  const env = readFileSync(join(import.meta.dir, "..", "..", ".env.local"), "utf8");
  const m = /^RUST_TS_DATA=(.*)$/m.exec(env);
  if (!m) throw new Error("RUST_TS_DATA not set");
  return m[1]!.trim();
}

const ROOT = join(import.meta.dir, "..", "..");
const upstream = arg("--upstream") ?? join(dataDir(), "rust");
const out = arg("--out") ?? join(ROOT, "src", "rustc_errors", "error_codes.gen.ts");
const pin = JSON.parse(readFileSync(join(ROOT, "UPSTREAM.json"), "utf8")) as { rust?: { commit?: string } };

// The generated file is stamped with the pin, so the checkout must be at the pin.
const pinCommit = pin.rust?.commit ?? "";
let head = "";
try {
  head = execFileSync("git", ["-C", upstream, "rev-parse", "HEAD"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
} catch {
  head = "";
}
if (pinCommit === "" || head !== pinCommit) {
  console.log(`ERROR: upstream checkout ${upstream} is at ${head || "?"}, UPSTREAM.json pins ${pinCommit || "?"}`);
  process.exit(1);
}

const src = readFileSync(join(upstream, "compiler", "rustc_error_codes", "src", "lib.rs"), "utf8");
const start = src.indexOf("$macro!(");
// The list ends at the first line that is only `);` (a `);` inside a comment does not end it).
const close = start < 0 ? null : /^[ \t]*\);[ \t]*$/m.exec(src.slice(start));
const end = close === null || start < 0 ? -1 : start + close.index;
if (start < 0 || end < 0) {
  console.log("ERROR: error_codes! macro body not found in rustc_error_codes/src/lib.rs");
  process.exit(1);
}
const codes: string[] = [];
for (const raw of src.slice(start + "$macro!(".length, end).split("\n")) {
  const line = raw.trim();
  if (line === "" || line.startsWith("//")) continue;
  // `0556, // REMOVED: ...`: a trailing comment does not remove the code from the macro input.
  const m = /^(\d{4}),\s*(\/\/.*)?$/.exec(line);
  if (!m) {
    console.log(`ERROR: unexpected line in error_codes!: ${line}`);
    process.exit(1);
  }
  codes.push(m[1]!);
}

const lines = [
  `// GENERATED by tools/codegen/error_codes.ts from compiler/rustc_error_codes/src/lib.rs @ ${pinCommit.slice(0, 12)}. Do not edit.`,
  "// The constants of `define_error_code_constants_and_diagnostics_table!` (compiler/rustc_errors/src/codes.rs).",
  'import { ErrCode } from "./codes.gen.ts";',
  "",
  ...codes.map((c) => `export const E${c}: ErrCode = ErrCode.from_u32(${Number(c)});`),
  "",
  "/** Every error code of `rustc_error_codes::error_codes!`, in macro order. */",
  "export const ERROR_CODES: readonly ErrCode[] = [",
  ...codes.map((c) => `  E${c},`),
  "];",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`error_codes: ${codes.length} codes (E${codes[0]}..E${codes[codes.length - 1]}) -> ${out}`);
